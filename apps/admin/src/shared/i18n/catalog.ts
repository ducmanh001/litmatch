export const messages = { vi: vietnamese, en: english } as const;

type ParameterNames<Text extends string> =
  Text extends `${string}{{${infer Parameter}}}${infer Rest}`
    ? Parameter | ParameterNames<Rest>
    : never;
type MessageParameters<Key extends MessageKey> = ParameterNames<
  (typeof vietnamese)[Key]
>;
type TranslationArguments<Key extends MessageKey> = [
  MessageParameters<Key>,
] extends [never]
  ? []
  : [parameters: Record<MessageParameters<Key>, string | number>];

export function translate<Key extends MessageKey>(
  locale: keyof typeof messages,
  key: Key,
  ...[parameters]: TranslationArguments<Key>
): string {
  const message = messages[locale][key];
  if (parameters === undefined) return message;
  return message.replace(/\{\{(\w+)\}\}/gu, (_, name: string) =>
    String(parameters[name as MessageParameters<Key>] ?? ''),
  );
}

export function t<Key extends MessageKey>(
  key: Key,
  ...parameters: TranslationArguments<Key>
): string {
  return translate(getLocale(), key, ...parameters);
}

export function useT(): <Key extends MessageKey>(
  key: Key,
  ...parameters: TranslationArguments<Key>
) => string {
  const locale = useLocale();
  return (key, ...parameters) => translate(locale, key, ...parameters);
}
